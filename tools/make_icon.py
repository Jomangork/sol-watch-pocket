"""Turn a 24×24 pixel design from the SOL Watch Icon Lab into the app's icon files.

    python3 tools/make_icon.py tools/icon/wristwatch-v2.txt

Writes, under android/app/src/main/res:
  drawable/ic_launcher_foreground.xml   the full-colour design, inside the adaptive icon's safe zone
  drawable/ic_launcher_monochrome.xml   one-colour version for Android's themed icons
  drawable/ic_notify.xml                white-only status-bar silhouette (24 dp)
  mipmap-anydpi-v26/ic_launcher.xml     the adaptive icon (night-navy background)
  values/ic_launcher_colors.xml         the background colour
Vector drawables made of whole-pixel squares, so the icon stays sharp at every size.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "android" / "app" / "src" / "main" / "res"

# The Icon Lab's palette ('.' is transparent).
PALETTE = {"n": "#0e1630", "m": "#1e2c58", "y": "#ffd65a", "o": "#f0a028", "w": "#fff3c0", "b": "#4696e6",
           "l": "#96d2ff", "r": "#ff5a4a", "g": "#465276", "k": "#141420", "c": "#e8eefc"}
BACKGROUND = "#0e1630"

# Adaptive icons are 108 dp with a 66 dp circle that is always shown; 24 px × 2.4 = 57.6 dp keeps
# even the design's corners inside that circle.
SCALE = 2.4
OFFSET = (108 - 24 * SCALE) / 2


def read(path):
    rows = [line.rstrip("\n") for line in Path(path).read_text().splitlines() if line.strip()]
    if len(rows) != 24 or any(len(r) != 24 for r in rows):
        sys.exit(f"{path}: need 24 rows of 24 characters")
    unknown = {ch for r in rows for ch in r} - set(PALETTE) - {"."}
    if unknown:
        sys.exit(f"{path}: unknown colours {sorted(unknown)}")
    return rows


def silhouette(rows):
    """The Icon Lab's white-only rule: dark colours become holes, and the sun is cut away just
    above the ring, so the ring stays readable in one colour."""
    out = []
    for j, row in enumerate(rows):
        line = ""
        for i, ch in enumerate(row):
            hole = ch in ".nmk" or (ch in "yow" and j < 23 and rows[j + 1][i] == "b")
            line += "." if hole else "#"
        out.append(line)
    return out


def path_data(rows, colour, scale, offset):
    """One path of unit squares (merged along each row) for every pixel of that colour."""
    parts = []
    for j, row in enumerate(rows):
        i = 0
        while i < len(row):
            if row[i] != colour:
                i += 1
                continue
            start = i
            while i < len(row) and row[i] == colour:
                i += 1
            x, y, w = offset + start * scale, offset + j * scale, (i - start) * scale
            parts.append(f"M{x:g},{y:g}h{w:g}v{scale:g}h{-w:g}z")
    return "".join(parts)


def vector(size_dp, viewport, paths):
    body = "\n".join(f'    <path android:fillColor="{colour}" android:pathData="{data}" />' for colour, data in paths if data)
    return (f'<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Generated by tools/make_icon.py; edit the pixel text, not this file. -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size_dp}dp" android:height="{size_dp}dp"\n'
            f'    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n{body}\n</vector>\n')


def main():
    rows = read(sys.argv[1] if len(sys.argv) > 1 else ROOT / "tools" / "icon" / "wristwatch-v2.txt")
    mono = silhouette(rows)
    (RES / "drawable").mkdir(parents=True, exist_ok=True)
    (RES / "mipmap-anydpi-v26").mkdir(parents=True, exist_ok=True)
    (RES / "values").mkdir(parents=True, exist_ok=True)

    colour_paths = [(PALETTE[ch], path_data(rows, ch, SCALE, OFFSET)) for ch in PALETTE]
    (RES / "drawable" / "ic_launcher_foreground.xml").write_text(vector(108, 108, colour_paths))
    (RES / "drawable" / "ic_launcher_monochrome.xml").write_text(
        vector(108, 108, [("#FFFFFFFF", path_data(mono, "#", SCALE, OFFSET))]))
    (RES / "drawable" / "ic_notify.xml").write_text(vector(24, 24, [("#FFFFFFFF", path_data(mono, "#", 1, 0))]))
    (RES / "values" / "ic_launcher_colors.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="ic_launcher_background">{BACKGROUND}</color>\n</resources>\n')
    (RES / "mipmap-anydpi-v26" / "ic_launcher.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        '</adaptive-icon>\n')
    print("\n".join(mono))


if __name__ == "__main__":
    main()
